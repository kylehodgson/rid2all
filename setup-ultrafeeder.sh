#!/usr/bin/env bash
# WellClear Remote ID setup — adds rid2all to an existing ultrafeeder
# (docker compose) install. One script, no manual file editing.
#
# What it does:
#   1. writes rid2all-config.toml (pushes SBS into ultrafeeder)
#   2. creates rid-db/ + copies the base aircraft db (keeps real-aircraft
#      reg/type lookups working on stations with an SDR)
#   3. writes docker-compose.override.yml — adds the rid2all service and the
#      ultrafeeder env/volume changes. YOUR docker-compose.yml is NOT touched
#      (compose auto-loads the override file).
#   4. docker compose up -d and verifies
#
# Usage:  sudo bash setup-ultrafeeder.sh [compose-dir]     (default: /opt/adsb)
# Re-run safe: everything is regenerated.
set -euo pipefail

COMPOSE_DIR=${1:-/opt/adsb}
IMAGE=ghcr.io/kylehodgson/rid2all:latest
OVER="$COMPOSE_DIR/docker-compose.override.yml"
CFG="$COMPOSE_DIR/rid2all-config.toml"
RIDDB="$COMPOSE_DIR/rid-db"
SBS_IN=32006   # ultrafeeder container-side SBS input port

msg()  { printf '\n== %s\n' "$*"; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# --- preflight ---------------------------------------------------------------
[ "$(id -u)" = 0 ] || die "run with sudo (needs docker + writing $COMPOSE_DIR)"
[ -d "$COMPOSE_DIR" ] || die "compose dir $COMPOSE_DIR not found (pass it: sudo bash $0 /path)"
cd "$COMPOSE_DIR"
BASE=$(ls docker-compose.yml compose.yml compose.yaml 2>/dev/null | head -1)
[ -n "$BASE" ] || die "no compose file in $COMPOSE_DIR"
grep -q "ultrafeeder" "$BASE" || die "no ultrafeeder service in $BASE — this installer targets ultrafeeder compose stacks"

DEV=/dev/ttyACM0
[ -e "$DEV" ] || die "no $DEV — plug in the DroneScout radio (USB) and re-run. (Check: ls /dev/ttyACM*)"
GID=$(stat -c %g "$DEV")
UID_=$(id -u 1000 >/dev/null 2>&1 && echo 1000 || echo 1000)
# docker group access check
docker info >/dev/null 2>&1 || die "docker not usable from this shell"

# --- 1. rid2all config -------------------------------------------------------
msg "writing $CFG"
if [ -d "$CFG" ]; then
    rm -rf "$CFG"   # docker made a directory here when the file was missing
fi
cat > "$CFG" <<EOF
# Generated by setup-ultrafeeder.sh — rid2all pushes SBS into ultrafeeder,
# which forwards drones to its configured aggregators (incl. wellclear.aero).
[source]
device = "$DEV"
baud = 115200

[[sbs.push]]
host = "ultrafeeder"
port = $SBS_IN

[track]
expire_seconds = 60
position_interval = 1.0
ident_interval = 30.0

[db]
output = "/rid-db/db.csv.gz"
base = "/rid-db/base-aircraft.csv.gz"

[log]
level = "info"
EOF

# --- 2. rid-db + base aircraft db --------------------------------------------
msg "rid-db dir + base aircraft db"
mkdir -p "$RIDDB"
if docker cp -L ultrafeeder:/usr/local/share/tar1090/aircraft.csv.gz "$RIDDB/base-aircraft.csv.gz" 2>/dev/null; then
    chown "$UID_":"$GID" "$RIDDB" "$RIDDB/base-aircraft.csv.gz" 2>/dev/null || true
    echo "base aircraft db copied ($(du -h "$RIDDB/base-aircraft.csv.gz" | cut -f1)) — real-aircraft reg/type lookups keep working"
else
    echo "WARN: could not copy base aircraft db (ultrafeeder not running?)."
    echo "      rid2all still works; real-aircraft db details in tar1090 will be"
    echo "      missing until you re-run this script with ultrafeeder up."
fi

# --- 3. compose override ------------------------------------------------------
msg "writing $OVER (your $BASE is NOT modified)"
if grep -q "READSB_EXTRA_ARGS" "$BASE"; then
    echo "NOTE: your compose already sets READSB_EXTRA_ARGS — the override value"
    echo "      below REPLACES it. Merge any existing flags manually if needed:"
    grep -n "READSB_EXTRA_ARGS" "$BASE" || true
fi
cat > "$OVER" <<EOF
# Auto-generated by setup-ultrafeeder.sh (WellClear Remote ID / rid2all).
# Adds: rid2all service, SBS input + drone-db on the ultrafeeder service.
# Compose auto-loads this override; do not rename. Safe to delete to uninstall.
services:
  ultrafeeder:
    environment:
      READSB_NET_SBS_INPUT_PORT: "$SBS_IN"
      # CONTAINER path — the volume below maps $RIDDB to /rid-db
      READSB_EXTRA_ARGS: "--db-file=/rid-db/db.csv.gz"
    volumes:
      - $RIDDB:/rid-db:ro

  rid2all:
    image: $IMAGE
    container_name: rid2all
    restart: unless-stopped
    # host uid for rid-db + the group that owns $DEV
    user: "$UID_:$GID"
    devices:
      - $DEV:$DEV
    volumes:
      - $CFG:/data/config.toml:ro
      - $RIDDB:/rid-db
EOF

# --- 4. up + verify -----------------------------------------------------------
msg "docker compose up -d"
docker compose up -d 2>&1 | grep -vE "^Network|^Container.*Running" | tail -4
sleep 10

msg "rid2all status"
docker logs rid2all --tail 6 2>&1 | sed 's/^/  /'
if docker logs rid2all 2>&1 | grep -q "sbs push connected"; then
    echo "  -> SBS push into ultrafeeder: CONNECTED"
else
    echo "  -> push not connected yet (ultrafeeder may still be starting; check docker logs rid2all in a minute)"
fi

msg "drone check (tar1090 aircraft list)"
if curl -fsS -m 10 http://localhost:8080/data/aircraft.json 2>/dev/null | grep -oq '"hex": *"ff[0-9a-f]*"'; then
    echo "  -> Remote ID drone(s) visible in ultrafeeder: YES"
    curl -fsS -m 10 http://localhost:8080/data/aircraft.json 2>/dev/null | python3 -c "
import json, sys
d = json.load(sys.stdin)
for a in d.get('aircraft', []):
    if a.get('hex', '').startswith('ff'):
        print('   ', a.get('hex'), a.get('flight', '').strip(), 'alt', a.get('alt_baro'), 'gs', a.get('gs'))" || true
else
    echo "  -> no drone in the air right now (or none in radio range) — that's fine."
fi

msg "Done."
echo "  - Drones ride your EXISTING aggregator feeds (incl. wellclear.aero) —"
echo "    they appear on the network map with FFxxxx hexes."
echo "  - Local map: http://$(hostname -I 2>/dev/null | awk '{print $1}'):8080/"
echo "  - Uninstall: docker compose down; rm $OVER; docker compose up -d"
